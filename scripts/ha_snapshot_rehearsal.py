"""Exact-byte rollback rehearsal for a disposable, synthetic HA config.

This CLI only accepts the public FAKE_HA_CONFIG generated by stage_ha_runtime.
It MUST NOT open or migrate a live Home Assistant config or .storage files.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from scripts.stage_ha_runtime import FAKE_HA_CONFIG

SCHEMA = "venta-ci-rehearsal/v1"
BASELINE = FAKE_HA_CONFIG.encode("utf-8")
PREFIX, SEPARATOR, _YAML = FAKE_HA_CONFIG.partition("\nventa_homekit_native:\n")
assert SEPARATOR, "synthetic Venta section missing"
CUTOVER = (PREFIX + "\n").encode("utf-8")
SYNTHETIC_ENTRY = {
    "domain": "venta_homekit_native",
    "source": "synthetic_fixture_only",
    "entry_id": "venta-ci-entry",
    "data": {
        "humidifier_entity": "humidifier.venta_ci_fake",
        "bridge_title": "Venta CI nonexistent bridge",
        "bridge_entry_id": "venta-ci-homekit-bridge",
        "fan_entity": "select.venta_ci_fan",
        "led_entity": "switch.venta_ci_led",
        "brightness_entity": "select.venta_ci_led_brightness",
        "temperature_entity": "sensor.venta_ci_temperature",
        "humidity_entity": "sensor.venta_ci_humidity",
    },
}


def digest(content: bytes) -> str:
    return hashlib.sha256(content).hexdigest()


def _safe_paths(config_dir: Path, state_dir: Path) -> Path:
    original = config_dir / "configuration.yaml"
    if (
        config_dir.is_symlink()
        or state_dir.is_symlink()
        or original.is_symlink()
        or ".storage" in config_dir.parts
        or ".storage" in state_dir.parts
        or config_dir.resolve().is_relative_to(state_dir.resolve())
        or state_dir.resolve().is_relative_to(config_dir.resolve())
    ):
        raise ValueError("unsafe_disposable_config_or_snapshot_path")
    if not original.is_file():
        raise ValueError("synthetic_configuration_missing")
    # An exact, known synthetic byte sequence is mandatory for capture.
    return original


def _read_backup(state_dir: Path) -> bytes:
    manifest = state_dir / "manifest.json"
    backup = state_dir / "configuration.yaml.original"
    if (
        state_dir.is_symlink()
        or manifest.is_symlink()
        or backup.is_symlink()
        or not manifest.is_file()
        or not backup.is_file()
        or manifest.stat().st_size > 4096
        or backup.stat().st_size > 16384
    ):
        raise ValueError("missing_or_invalid_fixture_backup")
    data = json.loads(manifest.read_text(encoding="utf-8"))
    expected = {
        "schema": SCHEMA,
        "type": "synthetic_only",
        "baseline_sha256": digest(BASELINE),
        "baseline_length": len(BASELINE),
    }
    contents = backup.read_bytes()
    if data != expected or contents != BASELINE or digest(contents) != data["baseline_sha256"]:
        raise ValueError("fixture_backup_integrity_failed")
    return contents


def rehearse(config_dir: Path, state_dir: Path, phase: str) -> dict:
    """Operate only on an exact fake YAML fixture, not real HA data."""
    original = _safe_paths(config_dir, state_dir)
    if phase == "capture":
        if original.read_bytes() != BASELINE or state_dir.exists():
            raise ValueError("capture_requires_pristine_synthetic_fixture")
        state_dir.mkdir(mode=0o700)
        (state_dir / "configuration.yaml.original").write_bytes(BASELINE)
        (state_dir / "manifest.json").write_text(
            json.dumps({
                "schema": SCHEMA,
                "type": "synthetic_only",
                "baseline_sha256": digest(BASELINE),
                "baseline_length": len(BASELINE),
            }, sort_keys=True) + "\n",
            encoding="utf-8",
        )
        assert _read_backup(state_dir) == BASELINE
    elif phase == "cutover":
        _read_backup(state_dir)
        if original.read_bytes() != BASELINE:
            raise ValueError("cutover_refuses_changed_or_real_yaml")
        # This is a fixture, NOT an HA ConfigEntry or a .storage migration.
        fixture = state_dir / "ui_entry_fixture.json"
        with fixture.open("x", encoding="utf-8") as output:
            json.dump(SYNTHETIC_ENTRY, output, sort_keys=True)
            output.write("\n")
        original.write_bytes(CUTOVER)
        assert original.read_bytes() == CUTOVER
    elif phase == "restore":
        saved = _read_backup(state_dir)
        fixture = state_dir / "ui_entry_fixture.json"
        if (
            original.read_bytes() != CUTOVER
            or fixture.is_symlink()
            or not fixture.is_file()
            or fixture.stat().st_size > 4096
            or json.loads(fixture.read_text(encoding="utf-8")) != SYNTHETIC_ENTRY
        ):
            raise ValueError("restore_requires_intact_synthetic_cutover")
        original.write_bytes(saved)
        assert digest(original.read_bytes()) == digest(BASELINE)
        fixture.unlink()
    else:
        raise ValueError("invalid_rehearsal_phase")
    return {
        "status": "PASS",
        "phase": phase,
        "source": "synthetic_only",
        "baseline_sha256": digest(BASELINE),
        "live_ha_modified": False,
        "pairings_touched": False,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--config", type=Path, required=True)
    parser.add_argument("--state", type=Path, required=True)
    parser.add_argument("--phase", choices=("capture", "cutover", "restore"), required=True)
    args = parser.parse_args()
    print(json.dumps(rehearse(args.config, args.state, args.phase), sort_keys=True))


if __name__ == "__main__":
    main()
